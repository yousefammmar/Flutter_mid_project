class Product{
  final String name;
  final double price;
  final String brand;
  final String category;
  final bool inStock;
  final String description;
  final String imagePath;
  const Product({
    required this.name,
    required this.price,
    required this.brand,
    required this.category,
    required this.inStock,
    required this.description,
    required this.imagePath,
  });
}